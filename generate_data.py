def get_first_letter(word):
    word = word.strip()
    if not word:
        return ""
    return word[0]
def generate_dataset():
    entries = []
    word_set = set()
    for cat_key, words in categories.items():
        cat_display = category_display.get(cat_key, cat_key)
        for word in words:
            word = word.strip()
            if not word or word in word_set:
                continue
            word_set.add(word)
            first_letter = get_first_letter(word)
            user_msg = f"یک {cat_display} که با حرف {first_letter} شروع شود بگو"
            entry = {
                "text": f"کاربر: {user_msg}\nدستیار: {word}"
            }
            entries.append(entry)
    print(f"Total words: {len(word_set)}")
    print(f"Total entries: {len(entries)}")
    random.seed(42)
    random.shuffle(entries)
    return entries, word_set
def save_jsonl(entries, filename="persian_words.jsonl"):
    with open(filename, "w", encoding="utf-8") as f:
        for entry in entries:
            f.write(json.dumps(entry, ensure_ascii=False) + "\n")
    print(f"Dataset saved to: {filename}")
if __name__ == "__main__":
    entries, word_set = generate_dataset()
